  /**
   * Быстрый поиск органов по подстроке
   * @param {string} query Введенный пользователем текст
   * @param {number} limit Максимальное количество подсказок
   * @returns {string[]} Массив подходящих органов
   */
  function searchBelarusOrgans(query, limit = 6) {
    if (!query || typeof query !== 'string') return [];
    const q = query.trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return [];

    // Приоритет:
    // 1. Начинается с искомого слова (например "моск" -> "Московское...")
    // 2. Искомое слово есть в названии города/района (например "минск", "гомель")
    // 3. Просто содержится в строке
    const exactStart = [];
    const wordStart = [];
    const contains = [];

    for (let i = 0; i < BELARUS_ORGANS.length; i++) {
      const item = BELARUS_ORGANS[i];
      const lower = item.toLowerCase().replace(/ё/g, 'е');

      if (lower.startsWith(q)) {
        exactStart.push(item);
      } else {
        const words = lower.split(/[\s,.-]+/);
        if (words.some(w => w.startsWith(q))) {
          wordStart.push(item);
        } else if (lower.includes(q)) {
          contains.push(item);
        }
      }

      if (exactStart.length + wordStart.length >= limit * 2) {
        break;
      }
    }

    const merged = [...exactStart, ...wordStart, ...contains];
    // Убираем дубликаты
    return Array.from(new Set(merged)).slice(0, limit);
  }

