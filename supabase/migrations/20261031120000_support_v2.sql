-- Короткий текст для списка обращений: «[Фото] подпись»
create or replace function public.support_preview(p_text text, p_media text) returns text
language sql immutable set search_path = public as $$
  select left(concat_ws(' ',
    case p_media when 'photo' then '[Фото]' when 'video' then '[Видео]' when 'document' then '[Файл]'
                 when 'voice' then '[Голосовое]' when 'audio' then '[Аудио]' when 'animation' then '[GIF]'
                 when 'sticker' then '[Стикер]' when 'video_note' then '[Видеосообщение]' end,
    nullif(btrim(p_text), '')), 200)
$$;

-- 3. Сводка обращения обновляется сама при каждом новом сообщении (бот, пульт и сервер пишут только сообщение)
create or replace function public.support_messages_after_insert() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.is_internal or new.delivery = 'failed' then
    update support_tickets set updated_at = now() where id = new.ticket_id;
  elsif new.sender_type = 'client' then
    update support_tickets set
      last_message_text = support_preview(new.text, new.media_type),
      last_message_at = new.created_at,
      last_sender = 'client',
      unread_by_operator = true,
      status = 'open',
      reminded_at = case when waiting_since is null then null else reminded_at end,
      autoreply_at = case when waiting_since is null then null else autoreply_at end,
      waiting_since = coalesce(waiting_since, new.created_at)
    where id = new.ticket_id;
  elsif new.sender_type = 'operator' then
    update support_tickets set
      last_message_text = support_preview(new.text, new.media_type),
      last_message_at = new.created_at,
      last_sender = 'operator',
      unread_by_operator = false,
      unread_by_client = true,
      status = case when status = 'closed' then 'closed' else 'in_progress' end,
      waiting_since = null,
      first_response_at = coalesce(first_response_at, new.created_at),
      operator_id = coalesce(operator_id, new.sender_id),
      card_dirty = true
    where id = new.ticket_id;
  else
    update support_tickets set last_message_at = new.created_at where id = new.ticket_id;
  end if;
  return new;
end $$;

drop trigger if exists support_messages_after_insert on public.support_messages;
create trigger support_messages_after_insert after insert on public.support_messages
  for each row execute function public.support_messages_after_insert();

-- Смена статуса или ответственного → карточку в боте операторов нужно перерисовать
create or replace function public.support_tickets_before_update() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  if new.status is distinct from old.status or new.operator_id is distinct from old.operator_id then
    new.card_dirty := true;
    if new.status = 'closed' then
      new.waiting_since := null;
      new.unread_by_operator := false;
      new.closed_at := coalesce(new.closed_at, now());
    elsif old.status = 'closed' then
      new.closed_at := null;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists support_tickets_before_update on public.support_tickets;
create trigger support_tickets_before_update before update on public.support_tickets
  for each row execute function public.support_tickets_before_update();

