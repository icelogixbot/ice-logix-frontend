-- 7. Команда поддержки: список и выдача роли (роль меняет только владелец)
create or replace function public.support_team()
returns table (user_id bigint, name text, username text, role text, notify boolean, has_login boolean)
language sql stable security definer set search_path = public as $$
  select u.user_id, u.full_name, u.username, u.role,
         coalesce((u.settings ->> 'support_notify')::boolean, u.role = 'support'),
         u.auth_id is not null
    from users u
   where u.role in ('owner', 'admin', 'support') and public.app_is_support()
   order by case u.role when 'owner' then 0 when 'admin' then 1 else 2 end, u.full_name nulls last
$$;

create or replace function public.support_set_operator(p_user bigint, p_on boolean) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_me text;
  v_target users%rowtype;
begin
  select role into v_me from users where auth_id = auth.uid();
  if v_me is distinct from 'owner' then
    raise exception 'Выдавать роль оператора может только владелец' using errcode = '42501';
  end if;
  select * into v_target from users where user_id = p_user or telegram_id = p_user limit 1;
  if not found then
    if not p_on then return 'not_found'; end if;
    insert into users (user_id, telegram_id, role, settings) values (p_user, p_user, 'support', jsonb_build_object('support_notify', true));
    return 'support';
  end if;
  if v_target.role in ('owner', 'admin') then
    raise exception 'У этого человека уже есть права администратора' using errcode = '42501';
  end if;
  update users set role = case when p_on then 'support' else 'user' end,
                   settings = coalesce(settings, '{}'::jsonb) || jsonb_build_object('support_notify', p_on)
   where user_id = v_target.user_id;
  return case when p_on then 'support' else 'user' end;
end $$;

-- Уведомления о новых обращениях: себе может включить любой сотрудник, другим — владелец
create or replace function public.support_set_notify(p_user bigint, p_on boolean) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  v_me users%rowtype;
begin
  select * into v_me from users where auth_id = auth.uid();
  if not found or v_me.role not in ('owner', 'admin', 'support') then
    raise exception 'Нет доступа' using errcode = '42501';
  end if;
  if p_user <> v_me.user_id and v_me.role <> 'owner' then
    raise exception 'Менять уведомления других может только владелец' using errcode = '42501';
  end if;
  update users set settings = coalesce(settings, '{}'::jsonb) || jsonb_build_object('support_notify', p_on)
   where user_id = p_user and role in ('owner', 'admin', 'support');
  return found;
end $$;

revoke all on function public.support_team(), public.support_set_operator(bigint, boolean), public.support_set_notify(bigint, boolean) from public, anon;
grant execute on function public.support_team(), public.support_set_operator(bigint, boolean), public.support_set_notify(bigint, boolean) to authenticated;
revoke all on function public.support_messages_after_insert(), public.support_tickets_before_update() from public, anon, authenticated;

